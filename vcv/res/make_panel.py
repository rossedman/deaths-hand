#!/usr/bin/env python3
"""Generates the panel SVG and a matching C++ layout header from one table.

    python3 res/make_panel.py          # writes res/ComplexOsc.svg + src/PanelLayout.hpp

Rack's SVG renderer ignores <text>, so labels are converted to outlines with
matplotlib's TextPath. Dimensions are real Eurorack (3U = 128.5 mm, 1 HP = 5.08 mm),
so the same file is a starting point for a physical front panel.
"""
from pathlib import Path

from matplotlib.font_manager import FontProperties
from matplotlib.path import Path as MPath
from matplotlib.textpath import TextPath

HP = 16
W, H = HP * 5.08, 128.5
COLS = [11.5, 30.8, 50.4, 69.8]

BG, FG, ACCENT, OUTBOX = "#1d1f24", "#e8e6e1", "#f2a541", "#2e3138"

# (kind, enum name, x, y, label)
#   kind: knob_l, knob_m, trim, snap, switch, in, out
CONTROLS = [
    ("knob_l", "PITCH_PARAM", COLS[0], 27, "PITCH"),
    ("knob_m", "FINE_PARAM", COLS[1], 27, "FINE"),
    ("knob_l", "MOD_PITCH_PARAM", COLS[2], 27, "RATIO/MOD"),
    ("knob_l", "FM_INDEX_PARAM", COLS[3], 27, "FM INDEX"),
    ("knob_m", "TIMBRE_PARAM", COLS[0], 47, "TIMBRE"),
    ("knob_m", "SYMMETRY_PARAM", COLS[1], 47, "SYMMETRY"),
    ("knob_m", "AM_PARAM", COLS[2], 47, "AM/RING"),
    ("knob_m", "TIMBRE_MOD_PARAM", COLS[3], 47, "T. MOD"),
    ("switch", "RATIO_LOCK_PARAM", COLS[0], 65, "LOCK"),
    ("snap", "MOD_SHAPE_PARAM", COLS[1], 65, "SHAPE"),
    ("trim", "FM_CV_ATTEN_PARAM", COLS[2], 65, "FM CV"),
    ("trim", "TIMBRE_CV_ATTEN_PARAM", COLS[3], 65, "TIM CV"),
    ("in", "VOCT_INPUT", COLS[0], 85, "V/OCT"),
    ("in", "MOD_VOCT_INPUT", COLS[1], 85, "MOD V/O"),
    ("in", "FM_INDEX_INPUT", COLS[2], 85, "INDEX"),
    ("in", "TIMBRE_INPUT", COLS[3], 85, "TIMBRE"),
    ("in", "SYMMETRY_INPUT", COLS[0], 101, "SYM"),
    ("in", "AM_INPUT", COLS[1], 101, "AM"),
    ("in", "EXT_FM_INPUT", COLS[2], 101, "EXT FM"),
    ("in", "SYNC_INPUT", COLS[3], 101, "SYNC"),
    ("out", "MOD_OUTPUT", COLS[2], 117, "MOD"),
    ("out", "PRIMARY_OUTPUT", COLS[3], 117, "OUT"),
]

LABEL_DY = {"knob_l": -8.6, "knob_m": -7.0, "trim": -5.6, "snap": -7.0, "switch": -6.6, "in": -6.2, "out": -6.2}
FONT = FontProperties(family="DejaVu Sans", weight="bold")


def text_path(s, x, y, size=2.2, anchor="middle", color=FG):
    """Text as an SVG <path>, (x, y) = baseline anchor, sizes in mm."""
    tp = TextPath((0, 0), s, size=size, prop=FONT)
    ext = tp.get_extents()
    dx = {"middle": -ext.width / 2 - ext.x0, "start": -ext.x0, "end": -ext.width - ext.x0}[anchor]
    d, i = [], 0
    verts, codes = tp.vertices, tp.codes
    while i < len(codes):
        c = codes[i]
        pt = lambda k: f"{x + dx + verts[k][0]:.3f},{y - verts[k][1]:.3f}"
        if c == MPath.MOVETO:
            d.append("M" + pt(i)); i += 1
        elif c == MPath.LINETO:
            d.append("L" + pt(i)); i += 1
        elif c == MPath.CURVE3:
            d.append("Q" + pt(i) + " " + pt(i + 1)); i += 2
        elif c == MPath.CURVE4:
            d.append("C" + pt(i) + " " + pt(i + 1) + " " + pt(i + 2)); i += 3
        elif c == MPath.CLOSEPOLY:
            d.append("Z"); i += 1
        else:
            i += 1
    return f'<path d="{"".join(d)}" fill="{color}"/>'


def svg():
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.2f}mm" height="{H}mm" viewBox="0 0 {W:.2f} {H}">',
        f'<rect width="{W:.2f}" height="{H}" fill="{BG}"/>',
        f'<rect x="0" y="0" width="{W:.2f}" height="1.2" fill="{ACCENT}"/>',
        f'<rect x="0" y="{H - 1.2}" width="{W:.2f}" height="1.2" fill="{ACCENT}"/>',
        text_path("COMPLEX OSC", W / 2, 10.5, size=4.2, color=FG),
        # Output well
        f'<rect x="{COLS[2] - 7.5:.2f}" y="106.5" width="{COLS[3] - COLS[2] + 15:.2f}" height="17" rx="1.6" fill="{OUTBOX}"/>',
        # Section rules
        f'<line x1="4" y1="74.5" x2="{W - 4:.2f}" y2="74.5" stroke="{OUTBOX}" stroke-width="0.4"/>',
    ]
    for kind, _, x, y, label in CONTROLS:
        out.append(text_path(label, x, y + LABEL_DY[kind], size=2.0, color=ACCENT if kind == "out" else FG))
    out.append(text_path("UP = RATIO", COLS[0], 73.0, size=1.5))
    out.append("</svg>")
    return "\n".join(out)


def header():
    lines = [
        "// Generated by res/make_panel.py — edit the table there, not here.",
        "#pragma once",
        "",
        "namespace panel {",
        "struct Pos { float x, y; }; // millimetres from the top-left",
    ]
    for kind, name, x, y, _ in CONTROLS:
        lines.append(f"constexpr Pos {name} = {{{x:.2f}f, {y:.2f}f}};")
    lines.append("} // namespace panel")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    (root / "res" / "ComplexOsc.svg").write_text(svg())
    (root / "src" / "PanelLayout.hpp").write_text(header())
    print(f"wrote {root / 'res/ComplexOsc.svg'} and {root / 'src/PanelLayout.hpp'} ({HP} HP)")
